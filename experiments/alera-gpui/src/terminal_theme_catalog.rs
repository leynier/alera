#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn catalog_matches_flutter_order_and_palettes() {
        assert_eq!(TERMINAL_THEME_NAMES.len(), 31);
        assert_eq!(TERMINAL_THEME_NAMES[0], "Alera Dark");
        assert_eq!(TERMINAL_THEME_NAMES[30], "Snazzy");
        assert_eq!(terminal_theme_palette("Tokyo Night").background, 0x1a1b26);
        assert_eq!(
            terminal_theme_palette("Builtin Tango Light").foreground,
            0x2e3434
        );
    }
}
